#!/usr/bin/env python3
"""Writes project-public-mac.yml: the App Store spec without the Apple Watch and iPhone widget targets.

The watch app ships only inside the iPhone app. Xcode still builds and signs an
explicit target dependency for Mac Catalyst even with platformFilter: ios, so the
Mac build and archive use this generated spec (project Parano1dPublicMac).
Plain text edits only, so the stock macOS python3 is enough.
"""
import re
import sys

lines = open('project-public.yml').read().splitlines()
drop_targets = {'Parano1dWatch', 'Parano1dWatchWidgets', 'Parano1dPhoneWidgets', 'Parano1dPublicTests'}
out, section, skipping, dep_indent = [], None, False, None
for line in lines:
    top = re.match(r'^(\w[\w-]*):', line)
    if top:
        section, skipping, dep_indent = top.group(1), False, None
        if section == 'name':
            out.append('name: Parano1dPublicMac'); continue
        if section == 'schemes':
            skipping = True
            out += ['schemes:', '  Parano1dPublicMac:', '    build:', '      targets:', '        Parano1dPublic: all']
            continue
        out.append(line); continue
    if section == 'schemes':
        continue
    if section == 'targets':
        target = re.match(r'^  (\w[\w-]*):\s*$', line)
        if target:
            skipping = target.group(1) in drop_targets
        if skipping:
            continue
        # Drop the "- target: Parano1dWatch" dependency entry and its indented body.
        dep = re.match(r'^(\s*)- target: (Parano1dWatch\w*|Parano1dPhoneWidgets)\s*$', line)
        if dep:
            dep_indent = len(dep.group(1)); continue
        if dep_indent is not None:
            if line.strip() and (len(line) - len(line.lstrip())) <= dep_indent:
                dep_indent = None
            else:
                continue
    out.append(line)
# The Mac menu bar shows the bundle name, so give the Mac app its readable name.
out = [l.replace('PRODUCT_NAME: Parano1dWallet', 'PRODUCT_NAME: "Parano1d Wallet"') for l in out]
text = '# Generated by Scripts/mac-spec.py from project-public.yml. Do not edit.\n' + '\n'.join(out) + '\n'
if 'Parano1dWatch' in text or 'Parano1dPhoneWidgets' in text or 'Parano1dPublic:' not in text:
    sys.exit('mac-spec.py: could not remove the watch targets cleanly.')
open('project-public-mac.yml', 'w').write(text)
print('Wrote project-public-mac.yml (no watch targets).')
